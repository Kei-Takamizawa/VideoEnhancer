import { expect, test } from "@playwright/test";
import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { desktop } from "../desktop";

test("S9: live changes after move and relaunch preserve safe old-copy removal", async () => {
  test.skip(!process.env.VE_GPU_TEST_MODEL_HOME, "Requires the isolated model cache.");
  test.setTimeout(180000);
  const root = path.resolve(".."), run = path.resolve(process.env.VE_GUI_TEST_ROOT || "../../scratch/P1t/e2e", `storage-restart-${Date.now()}`);
  const old = path.join(run, "seed/home"), target = path.join(run, "moved");
  execFileSync(path.join(root, ".venv/Scripts/python.exe"), ["tests/storage_seed.py", path.join(run, "seed"), process.env.VE_GPU_TEST_MODEL_HOME!], { cwd: root, timeout: 60000 });
  writeFileSync(path.join(old, "live.log"), "old log");
  writeFileSync(path.join(old, "same-size.txt"), "first");
  writeFileSync(path.join(old, "diagnostics.json"), "{torn diagnostic record");
  const env = { ...process.env, VE_HOME: undefined, VE_TEST_EXPECTED_HOME: old, VE_ENGINE_ROOT: root,
    VE_TEST_APPDATA: path.join(run, "roaming"), VE_TEST_LOCALAPPDATA: path.join(run, "local") };
  const pointer = path.join(env.VE_TEST_APPDATA, "VideoEnhancer/storage-location.json");
  mkdirSync(path.dirname(pointer), { recursive: true });
  writeFileSync(pointer, JSON.stringify({ active: old }));
  const args = [`--user-data-dir=${path.join(run, "desktop")}`];
  let app = await desktop.launch({ env, args });
  try {
    let page = await app.firstWindow();
    await expect(page.getByRole("button", { name: "Settings", exact: true })).toBeVisible({ timeout: 40000 });
    await page.evaluate(() => window.desktop.connection());
    const damaged = path.join(old, "previews/damaged-startup/state.json");
    mkdirSync(path.dirname(damaged), { recursive: true });
    writeFileSync(damaged, "{torn startup record");
    const savedPointer = readFileSync(pointer);
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    await app.files([target]);
    await page.getByRole("button", { name: "Move…", exact: true }).click();
    await expect(page.getByText("Move stopped. A file the app needs at start is damaged: previews/damaged-startup/state.json. Your data stays in the current folder.", { exact: true })).toBeVisible();
    expect(readFileSync(pointer)).toEqual(savedPointer);
    expect(readFileSync(damaged, "utf8")).toBe("{torn startup record");
    expect(readFileSync(path.join(old, "live.log"), "utf8")).toBe("old log");
    expect(existsSync(target)).toBe(false);
    unlinkSync(damaged);
    const moved = await page.evaluate(folder => window.desktop.moveStorage!(folder), target) as { damaged: Record<string, number> };
    expect(moved.damaged["diagnostics.json"]).toBe(1);
    expect(readFileSync(path.join(target, "diagnostics.json"), "utf8")).toBe("{torn diagnostic record");
    await app.quit();
    await app.close();
    app = await desktop.launch({ env: { ...env, VE_TEST_EXPECTED_HOME: target }, args });
    page = await app.firstWindow();
    await expect(page.getByRole("button", { name: "Settings", exact: true })).toBeVisible({ timeout: 40000 });
    appendFileSync(path.join(target, "live.log"), "\nnew live data");
    await page.evaluate(async () => {
      const c = await window.desktop.connection();
      const response = await fetch(`${c.base_url}/history/remove`, { method: "POST", headers: { Authorization: `Bearer ${c.token}`, "Content-Type": "application/json" }, body: JSON.stringify({ ids: ["finished"], history: true, original: false, output: false }) });
      if (!response.ok) throw new Error(await response.text());
    });
    await page.getByRole("button", { name: "Settings", exact: true }).click();
    const remove = page.getByRole("button", { name: "Remove the old folder", exact: true });
    await expect(remove).toBeEnabled({ timeout: 20000 });
    const probe = path.join(target, `.ve-storage-write-check-${app.process().pid}`);
    mkdirSync(probe);
    await expect(remove).toBeDisabled();
    execFileSync(path.join(root, ".venv/Scripts/python.exe"), ["-c", "import pathlib,sys; pathlib.Path(sys.argv[1]).rmdir()", probe]);
    await expect(remove).toBeEnabled();
    const settings = path.join(target, "settings.json"), saved = readFileSync(settings);
    writeFileSync(settings, "{broken");
    await expect(remove).toBeDisabled();
    writeFileSync(settings, saved);
    await expect(remove).toBeEnabled();
    appendFileSync(path.join(old, "live.log"), "\nchanged old copy");
    writeFileSync(path.join(old, "same-size.txt"), "other");
    writeFileSync(path.join(old, "unlisted.txt"), "keep unknown file");
    await app.command("remove-confirmation", false);
    await remove.click();
    expect(existsSync(path.join(old, "settings.json"))).toBe(true);
    await app.command("remove-confirmation", true);
    await remove.click();
    await expect(page.getByText(/Removed \d+ files/)).toBeVisible({ timeout: 30000 });
    expect(existsSync(path.join(old, "settings.json"))).toBe(false);
    expect(readFileSync(path.join(old, "live.log"), "utf8")).toContain("changed old copy");
    expect(existsSync(path.join(old, "unlisted.txt"))).toBe(true);
    expect(readFileSync(path.join(old, "same-size.txt"), "utf8")).toBe("other");
    expect(readFileSync(path.join(target, "live.log"), "utf8")).toContain("new live data");
    expect(JSON.parse(readFileSync(pointer, "utf8")).previous).toBeUndefined();
    await app.quit();
    await app.close();
    app = await desktop.launch({ env: { ...env, VE_TEST_EXPECTED_HOME: target }, args });
    const reopened = await app.firstWindow();
    await expect(reopened.getByRole("heading", { name: "Home", exact: true })).toBeVisible({ timeout: 40000 });
    expect(JSON.parse(readFileSync(pointer, "utf8")).active).toBe(target);
  } finally { await app.close(); }
});
